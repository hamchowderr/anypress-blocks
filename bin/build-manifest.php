<?php
/**
 * Writes blocks-manifest.php: every block's block.json in one PHP array, the format of @wordpress/scripts'
 * build-blocks-manifest, so WordPress registers all the blocks without reading and decoding each block.json
 * on every request (wp_register_block_types_from_metadata_collection, WordPress 6.8+).
 *
 *   php bin/build-manifest.php           write the manifest
 *   php bin/build-manifest.php --check   fail if the manifest is out of date (CI)
 */

$root     = dirname( __DIR__ );
$manifest = array();
foreach ( glob( $root . '/blocks/*/block.json' ) as $file ) {
	$manifest[ basename( dirname( $file ) ) ] = json_decode( file_get_contents( $file ), true );
}
ksort( $manifest );

$php = "<?php\n// Generated by bin/build-manifest.php from blocks/*/block.json: edit those and run the script, not this file.\nreturn " . var_export( $manifest, true ) . ";\n";
$out = $root . '/blocks-manifest.php';

if ( in_array( '--check', $argv, true ) ) {
	if ( ! is_file( $out ) || file_get_contents( $out ) !== $php ) {
		fwrite( STDERR, "blocks-manifest.php is out of date: run php bin/build-manifest.php\n" );
		exit( 1 );
	}
	echo "blocks-manifest.php is up to date\n";
	exit( 0 );
}

file_put_contents( $out, $php );
echo 'Wrote blocks-manifest.php (' . count( $manifest ) . " blocks)\n";
